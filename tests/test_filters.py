class TestSpatialLabels:
    """``spatial_labels`` builds the ``{en_label: display_label}`` dict that
    powers the spatial facet sidebar — exercised in both languages because
    the FR query path historically broke on a DuckDB GROUP BY constraint."""

    @pytest.fixture
    def bilingual_store(self) -> sc.Catalog:
        s = sc.Catalog().open()
        s.put(
            sc.OpenDataset(
                identifier="SL-DS1",
                title=_i("GDP", "PIB"),
                description=_i("desc", "description"),
                spatial_coverage=[
                    sc.SpatialCoverage(label=_i("Canada", "Canada")),
                    sc.SpatialCoverage(label=_i("Ontario", "Ontario")),
                ],
            )
        )
        s.put(
            sc.OpenDataset(
                identifier="SL-DS2",
                title=_i("Employment", "Emploi"),
                description=_i("desc2", "description2"),
                spatial_coverage=[
                    sc.SpatialCoverage(label=_i("Quebec", "Québec")),
                ],
            )
        )
        return s

    def test_en_returns_empty(self, bilingual_store: sc.Catalog) -> None:
        # EN is the canonical key in the dict that callers iterate, so an
        # empty mapping signals "nothing to remap" — not "no data".
        assert bilingual_store.spatial_labels("en") == {}

    def test_fr_maps_en_labels_to_fr(self, bilingual_store: sc.Catalog) -> None:
        labels = bilingual_store.spatial_labels("fr")
        assert labels == {"Canada": "Canada", "Ontario": "Ontario", "Quebec": "Québec"}

    def test_fr_falls_back_to_en_when_missing(self) -> None:
        s = sc.Catalog().open()
        s.put(
            sc.OpenDataset(
                identifier="SL-EN-ONLY",
                title=InternationalString(en="x"),
                description=InternationalString(en="y"),
                spatial_coverage=[sc.SpatialCoverage(label=InternationalString(en="Yukon"))],
            )
        )
        labels = s.spatial_labels("fr")
        assert labels == {"Yukon": "Yukon"}


def test_spatial_labels_pick_one_label_per_uri() -> None:
    """Rows sharing a uri with no concept but different labels give the least, every call."""
    store = sc.Catalog().open()
    store.put(
        [
            sc.OpenDataset(
                identifier=ident,
                title=InternationalString(en=ident),
                description=InternationalString(en=ident),
                spatial_coverage=[sc.SpatialCoverage(uri="urn:geo:x", label=InternationalString(fr=label))],
            )
            for ident, label in (("a", "Zone B"), ("b", "Zone A"))
        ]
    )
    assert store.spatial_labels("fr") == {"urn:geo:x": "Zone A"}
