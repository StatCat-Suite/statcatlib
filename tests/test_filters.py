# Identifier generated by ingest_sdmx for maintainer=AGG, id=FILTER
_AGG_ID = "AGG:FILTER(1.0)"
# Endpoint of the data service behind the aggregate dataset's CSV distribution
_SVC_URL = "https://api.example.com/sdmx"


