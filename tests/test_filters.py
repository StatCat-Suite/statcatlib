def _i(en: str, fr: str | None = None) -> InternationalString:
    return InternationalString(en=en, fr=fr or en)


def _make_store() -> sc.Catalog:
    """A store with two datasets: one aggregate (via SDMX ingest), one open."""
    import attrs

    s = sc.Catalog().open()

    # Build SDMX registry: DSD with GEO=[ON,QC] and SEX=[M,F] dimensions
    cl_geo = Codelist(
        id="CL_GEO",
        maintainer="AGG",
        name=_i("Geography"),
        codes=[Code(id="ON", name=_i("Ontario")), Code(id="QC", name=_i("Quebec"))],
    )
    cl_sex = Codelist(
        id="CL_SEX",
        maintainer="AGG",
        name=_i("Sex"),
        codes=[Code(id="M", name=_i("Male")), Code(id="F", name=_i("Female"))],
    )
    dsd = DataStructure(
        id="DSD_FILTER",
        maintainer="AGG",
        name=_i("Filter DSD"),
        dimensions=[
            Dimension(id="GEO", concept=concept_of("GEO"), representation=cl_geo),
            Dimension(id="SEX", concept=concept_of("SEX"), representation=cl_sex),
        ],
    )
    flow = Dataflow(
        id="FILTER",
        maintainer="AGG",
        name=_i("Aggregate Dataset"),
        description=_i("For filter tests"),
        structure=dsd,
    )
    registry = InMemoryRegistry()
    for obj in [cl_geo, cl_sex, dsd, flow]:
        registry.add(obj)

    datasets = sc.ingest_sdmx(s, registry)
    # Evolve to add distributions (ingest gives us a plain AggregateDataset)
    agg_base = datasets[0]
    agg = attrs.evolve(
        agg_base,
        publisher=sc.Agent(id="PUB", name=_i("Publisher")),
        distributions=[
            sc.Distribution(
                id="AGG-DIST-CSV",
                access_url="http://example.com/agg.csv",
                media_type="text/csv",
                format="CSV",
                access_service=sc.DataService(
                    id="SVC-AGG",
                    title=_i("Aggregate API"),
                    endpoint_url=_SVC_URL,
                ),
            ),
            sc.Distribution(
                id="AGG-DIST-JSON",
                access_url="http://example.com/agg.json",
                media_type="application/json",
                format="JSON",
            ),
        ],
    )
    s.put(agg)

    plain = sc.OpenDataset(
        identifier="OPEN-FILTER",
        title=_i("Open Dataset"),
        description=_i("For filter tests"),
        distributions=[
            sc.Distribution(
                id="OPEN-DIST-CSV",
                access_url="http://example.com/open.csv",
                media_type="text/csv",
                format="CSV",
            ),
        ],
    )
    s.put(plain)

    return s


